-- 1. Tabuľky

-- USERS: profil používateľa prepojený s auth.users
CREATE TABLE IF NOT EXISTS public.users (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  "fullName" text,
  email text,
  role text NOT NULL DEFAULT 'user',
  "phoneNumber" text,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- TRAININGS: tréningy
CREATE TABLE IF NOT EXISTS public.trainings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type text NOT NULL,
  datetime timestamp NOT NULL,
  note text,
  "minParticipants" integer,
  "maxParticipants" integer,
  "unregisterDeadline" timestamp,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- TRAINING_REGISTRATIONS: prihlásenia používateľov na tréningy
CREATE TABLE IF NOT EXISTS public.training_registrations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  training_id bigint NOT NULL REFERENCES public.trainings(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  registered_at timestamptz NOT NULL DEFAULT now(),
  cancelled_at timestamptz,
  UNIQUE(training_id, user_id)
);

-- Migrácia: zlúč date + time do datetime (pre existujúce DB)
DO $$
BEGIN
  -- Pridaj datetime ak neexistuje
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'trainings' AND column_name = 'datetime'
  ) THEN
    ALTER TABLE public.trainings ADD COLUMN datetime timestamp;
  END IF;

  -- Ak existujú staré stĺpce date a time, zlúč ich do datetime
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'trainings' AND column_name = 'date'
  ) THEN
    UPDATE public.trainings SET datetime = (date + time) WHERE datetime IS NULL;
    ALTER TABLE public.trainings ALTER COLUMN datetime SET NOT NULL;
    ALTER TABLE public.trainings DROP COLUMN date;
    ALTER TABLE public.trainings DROP COLUMN time;
  END IF;

  -- Pridaj unregisterDeadline ak neexistuje
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'trainings' AND column_name = 'unregisterDeadline'
  ) THEN
    ALTER TABLE public.trainings ADD COLUMN "unregisterDeadline" timestamp;
  END IF;
END $$;

-- Zmeň unregisterDeadline z timestamptz na timestamp ak treba
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'trainings' AND column_name = 'unregisterDeadline' AND data_type = 'timestamp with time zone'
  ) THEN
    ALTER TABLE public.trainings ALTER COLUMN "unregisterDeadline" TYPE timestamp USING "unregisterDeadline" AT TIME ZONE 'Europe/Bratislava';
  END IF;
END $$;

-- Ak type bol enum, zmeň na text
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'trainings' AND column_name = 'type' AND data_type = 'USER-DEFINED'
  ) THEN
    ALTER TABLE public.trainings ALTER COLUMN type TYPE text;
  END IF;
END $$;
DROP TYPE IF EXISTS training_type;

-- 2. Trigger: po registrácii automaticky vytvorí záznam v public.users

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger AS $$
DECLARE
  _name text;
BEGIN
  -- Meno: najprv first_name + last_name (registrácia), potom name (Google OAuth), potom full_name
  _name := TRIM(COALESCE(NEW.raw_user_meta_data->>'first_name', '') || ' ' || COALESCE(NEW.raw_user_meta_data->>'last_name', ''));
  IF _name = '' OR _name IS NULL THEN
    _name := COALESCE(NEW.raw_user_meta_data->>'name', '');
  END IF;
  IF _name = '' OR _name IS NULL THEN
    _name := COALESCE(NEW.raw_user_meta_data->>'full_name', '');
  END IF;

  INSERT INTO public.users (id, email, "fullName", "phoneNumber", role)
  VALUES (
    NEW.id,
    NEW.email,
    _name,
    COALESCE(NEW.raw_user_meta_data->>'phone_number', NULL),
    'user'
  );
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- 3. RLS politiky

ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.trainings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.training_registrations ENABLE ROW LEVEL SECURITY;

-- USERS: každý prihlásený vidí len svoj riadok
DROP POLICY IF EXISTS "Users can view own profile" ON public.users;
CREATE POLICY "Users can view own profile"
  ON public.users FOR SELECT
  TO authenticated
  USING (auth.uid() = id);

DROP POLICY IF EXISTS "Admin can view all users" ON public.users;

-- USERS: user môže aktualizovať len vlastný profil (nemôže zmeniť role)
DROP POLICY IF EXISTS "Users can update own profile" ON public.users;
CREATE POLICY "Users can update own profile"
  ON public.users FOR UPDATE
  TO authenticated
  USING (auth.uid() = id)
  WITH CHECK (auth.uid() = id AND role = 'user');

-- TRAININGS: authenticated user môže SELECT
DROP POLICY IF EXISTS "Authenticated users can view trainings" ON public.trainings;
CREATE POLICY "Authenticated users can view trainings"
  ON public.trainings FOR SELECT
  TO authenticated
  USING (true);

-- TRAININGS: len admin môže INSERT
DROP POLICY IF EXISTS "Admin can insert trainings" ON public.trainings;
CREATE POLICY "Admin can insert trainings"
  ON public.trainings FOR INSERT
  TO authenticated
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.users u
      WHERE u.id = auth.uid() AND u.role = 'admin'
    )
  );

-- TRAININGS: len admin môže UPDATE
DROP POLICY IF EXISTS "Admin can update trainings" ON public.trainings;
CREATE POLICY "Admin can update trainings"
  ON public.trainings FOR UPDATE
  TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.users u
      WHERE u.id = auth.uid() AND u.role = 'admin'
    )
  );

-- TRAININGS: len admin môže DELETE
DROP POLICY IF EXISTS "Admin can delete trainings" ON public.trainings;
CREATE POLICY "Admin can delete trainings"
  ON public.trainings FOR DELETE
  TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.users u
      WHERE u.id = auth.uid() AND u.role = 'admin'
    )
  );

-- TRAININGS: anon môžu čítať tréningy (pre verejný kalendár)
DROP POLICY IF EXISTS "Anon can view trainings" ON public.trainings;
CREATE POLICY "Anon can view trainings"
  ON public.trainings FOR SELECT
  TO anon
  USING (true);

-- TRAINING_REGISTRATIONS: user vidí svoje registrácie
DROP POLICY IF EXISTS "Users can view own registrations" ON public.training_registrations;
CREATE POLICY "Users can view own registrations"
  ON public.training_registrations FOR SELECT
  TO authenticated
  USING (auth.uid() = user_id);

-- TRAINING_REGISTRATIONS: user sa môže prihlásiť na tréning
DROP POLICY IF EXISTS "Users can register for training" ON public.training_registrations;
CREATE POLICY "Users can register for training"
  ON public.training_registrations FOR INSERT
  TO authenticated
  WITH CHECK (auth.uid() = user_id);

-- TRAINING_REGISTRATIONS: user sa môže odhlásiť (UPDATE cancelled_at)
DROP POLICY IF EXISTS "Users can cancel own registration" ON public.training_registrations;
CREATE POLICY "Users can cancel own registration"
  ON public.training_registrations FOR UPDATE
  TO authenticated
  USING (auth.uid() = user_id);

-- TRAINING_REGISTRATIONS: admin vidí všetky registrácie
DROP POLICY IF EXISTS "Admin can view all registrations" ON public.training_registrations;
CREATE POLICY "Admin can view all registrations"
  ON public.training_registrations FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.users u
