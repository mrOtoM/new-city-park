-- 1. Waitlist
-- A separate table, not a status on training_registrations, so active_count,
-- statistics, and the participant list keep their meaning.
-- notified_at is the "spot opened" flag: set when the person was e-mailed,
-- cleared when the training fills up again, so each opening mails once.

CREATE TABLE IF NOT EXISTS public.training_waitlist (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  training_id bigint NOT NULL REFERENCES public.trainings(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  joined_at timestamptz NOT NULL DEFAULT now(),
  notified_at timestamptz,
  UNIQUE (training_id, user_id)
);

ALTER TABLE public.training_waitlist ENABLE ROW LEVEL SECURITY;

-- Writes go through the functions below only; there is deliberately no
-- INSERT, UPDATE, or DELETE policy.
DROP POLICY IF EXISTS "Users can view own waitlist entries" ON public.training_waitlist;
CREATE POLICY "Users can view own waitlist entries"
  ON public.training_waitlist FOR SELECT
  TO authenticated
  USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Admin can view all waitlist entries" ON public.training_waitlist;
CREATE POLICY "Admin can view all waitlist entries"
  ON public.training_waitlist FOR SELECT
  TO authenticated
  USING (public.has_admin_capabilities());

REVOKE ALL ON TABLE public.training_waitlist FROM anon, authenticated;
GRANT SELECT ON TABLE public.training_waitlist TO authenticated;

-- 2. Waitlist size
