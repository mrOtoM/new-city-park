-- read it, so changing it is a one-line migration with no deploy.

CREATE OR REPLACE FUNCTION public.waitlist_capacity()
RETURNS integer
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT 5;
$$;

REVOKE ALL ON FUNCTION public.waitlist_capacity() FROM public, anon;
GRANT EXECUTE ON FUNCTION public.waitlist_capacity() TO authenticated;

-- 3. Occupancy view
-- Columns are appended, which is the only change CREATE OR REPLACE VIEW
-- accepts. Both additions are counts; the no-PII rule of this view still holds.

CREATE OR REPLACE VIEW public.training_capacity
WITH (security_invoker = off) AS
SELECT
  t.id AS training_id,
  t."maxParticipants" AS max_participants,
  count(r.id) FILTER (WHERE r.cancelled_at IS NULL) AS active_count,
  (SELECT count(*) FROM public.training_waitlist w WHERE w.training_id = t.id) AS waitlist_count,
  public.waitlist_capacity() AS waitlist_max
FROM public.trainings t
LEFT JOIN public.training_registrations r ON r.training_id = t.id
GROUP BY t.id, t."maxParticipants";

REVOKE ALL ON public.training_capacity FROM anon;
GRANT SELECT ON public.training_capacity TO authenticated;

-- 4. Joining and leaving
-- Same shape as register_for_training: the training row is locked so a join
-- and a concurrent registration see a consistent count.

CREATE OR REPLACE FUNCTION public.join_training_waitlist(p_training_id bigint)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  _user uuid := auth.uid();
  _max integer;
  _starts_at timestamp;
  _active integer;
  _waiting integer;
BEGIN
  IF _user IS NULL THEN
    RETURN 'unauthenticated';
  END IF;

  SELECT t."maxParticipants", t.datetime
  INTO _max, _starts_at
  FROM public.trainings t
  WHERE t.id = p_training_id
  FOR UPDATE;

  IF _starts_at IS NULL THEN
    RETURN 'not_found';
  END IF;

  IF _starts_at <= (now() AT TIME ZONE 'Europe/Bratislava') THEN
    RETURN 'past';
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.training_registrations r
    WHERE r.training_id = p_training_id AND r.user_id = _user AND r.cancelled_at IS NULL
  ) THEN
    RETURN 'already_registered';
  END IF;

  IF _max IS NULL THEN
    RETURN 'not_full';
  END IF;

  SELECT count(*)
  INTO _active
  FROM public.training_registrations r
  WHERE r.training_id = p_training_id AND r.cancelled_at IS NULL;

  IF _active < _max THEN
    RETURN 'not_full';
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.training_waitlist w
    WHERE w.training_id = p_training_id AND w.user_id = _user
  ) THEN
    RETURN 'already_waitlisted';
  END IF;

  SELECT count(*)
  INTO _waiting
  FROM public.training_waitlist w
  WHERE w.training_id = p_training_id;

  IF _waiting >= public.waitlist_capacity() THEN
    RETURN 'waitlist_full';
  END IF;

  INSERT INTO public.training_waitlist (training_id, user_id)
  VALUES (p_training_id, _user);

  RETURN 'ok';
END;
$$;

CREATE OR REPLACE FUNCTION public.leave_training_waitlist(p_training_id bigint)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  _user uuid := auth.uid();
BEGIN
  IF _user IS NULL THEN
    RETURN 'unauthenticated';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.trainings t WHERE t.id = p_training_id) THEN
    RETURN 'not_found';
  END IF;

  DELETE FROM public.training_waitlist
  WHERE training_id = p_training_id AND user_id = _user;

  IF NOT FOUND THEN
    RETURN 'not_waitlisted';
  END IF;

  RETURN 'ok';
END;
$$;

REVOKE ALL ON FUNCTION public.join_training_waitlist(bigint) FROM public, anon;
REVOKE ALL ON FUNCTION public.leave_training_waitlist(bigint) FROM public, anon;
GRANT EXECUTE ON FUNCTION public.join_training_waitlist(bigint) TO authenticated;
GRANT EXECUTE ON FUNCTION public.leave_training_waitlist(bigint) TO authenticated;

-- 5. Registration
-- Identical to 20260902073053 up to the insert; then the caller leaves the
-- waitlist, and if this registration filled the training the "spot opened"
-- flags are cleared so the next opening notifies again.

CREATE OR REPLACE FUNCTION public.register_for_training(p_training_id bigint)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  _user uuid := auth.uid();
  _max integer;
  _starts_at timestamp;
  _active integer;
  _existing_id bigint;
  _existing_cancelled timestamptz;
BEGIN
  IF _user IS NULL THEN
    RETURN 'unauthenticated';
  END IF;

  SELECT t."maxParticipants", t.datetime
  INTO _max, _starts_at
  FROM public.trainings t
  WHERE t.id = p_training_id
  FOR UPDATE;

  IF _starts_at IS NULL THEN
    RETURN 'not_found';
  END IF;

  IF _starts_at <= (now() AT TIME ZONE 'Europe/Bratislava') THEN
    RETURN 'past';
  END IF;

  SELECT r.id, r.cancelled_at
  INTO _existing_id, _existing_cancelled
  FROM public.training_registrations r
  WHERE r.training_id = p_training_id AND r.user_id = _user;

  IF _existing_id IS NOT NULL AND _existing_cancelled IS NULL THEN
    RETURN 'already_registered';
  END IF;

  IF _max IS NOT NULL THEN
    SELECT count(*)
    INTO _active
    FROM public.training_registrations r
    WHERE r.training_id = p_training_id AND r.cancelled_at IS NULL;

    IF _active >= _max THEN
      RETURN 'full';
    END IF;
  END IF;

  IF _existing_id IS NOT NULL THEN
    UPDATE public.training_registrations
    SET cancelled_at = NULL, registered_at = now()
    WHERE id = _existing_id;
  ELSE
    INSERT INTO public.training_registrations (training_id, user_id)
    VALUES (p_training_id, _user);
  END IF;

  DELETE FROM public.training_waitlist
  WHERE training_id = p_training_id AND user_id = _user;

  IF _max IS NOT NULL AND _active + 1 >= _max THEN
    UPDATE public.training_waitlist
    SET notified_at = NULL
    WHERE training_id = p_training_id;
  END IF;

  RETURN 'ok';
END;
$$;

REVOKE ALL ON FUNCTION public.register_for_training(bigint) FROM public, anon;
GRANT EXECUTE ON FUNCTION public.register_for_training(bigint) TO authenticated;

-- 6. Notification recipients
-- Returns other users' names and e-mails, so no user session may call it:
-- only service_role, from the server, after the caller's own write succeeded.
-- Approved as a system operation in docs/02-authentication-authorization-overview.md.
-- Marking notified_at in the same statement makes repeated calls while the
-- spot stays open return nothing.

CREATE OR REPLACE FUNCTION public.claim_waitlist_notifications(p_training_id bigint)
RETURNS TABLE (name text, email text)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  _max integer;
  _starts_at timestamp;
  _active integer;
BEGIN
  SELECT t."maxParticipants", t.datetime
  INTO _max, _starts_at
  FROM public.trainings t
  WHERE t.id = p_training_id
  FOR UPDATE;

  IF _starts_at IS NULL OR _max IS NULL OR _starts_at <= (now() AT TIME ZONE 'Europe/Bratislava') THEN
    RETURN;
  END IF;

  SELECT count(*)
  INTO _active
  FROM public.training_registrations r
  WHERE r.training_id = p_training_id AND r.cancelled_at IS NULL;

  IF _active >= _max THEN
    RETURN;
  END IF;

  RETURN QUERY
  WITH claimed AS (
    UPDATE public.training_waitlist w
    SET notified_at = now()
    WHERE w.training_id = p_training_id AND w.notified_at IS NULL
    RETURNING w.user_id
  )
  SELECT u."fullName", u.email
  FROM claimed c
  JOIN public.users u ON u.id = c.user_id
  WHERE u.email IS NOT NULL;
END;
$$;

REVOKE ALL ON FUNCTION public.claim_waitlist_notifications(bigint) FROM public, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.claim_waitlist_notifications(bigint) TO service_role;
